def structural_records(text, row, scope, *, resolved_quantities=()):
    restrictions=[]
    for sentence in re.finditer(r'[^。\r\n]+',text):
        raw=sentence[0].strip()
        masked=re.sub(r'「[^」]*」|『[^』]*』',lambda m:' '*len(m[0]),raw)
        selection_clause = masked
        for source in resolved_quantities:
            selection_clause = selection_clause.replace(source, ' ' * len(source))
        for kind,label,pattern in RESTRICTIONS:
            scan=selection_clause if kind=='selection_limit' else masked
            if kind=='cannot_summon':
                scan=re.sub(r'不能(?:为[^。]{0,45}上级召唤(?:以外)?而解放|作为[^。]{0,40}祭品召唤的祭品)',lambda m:' '*len(m[0]),scan)
            clauses=re.split(r'[，,]',scan) if kind in ('cannot_activate','cannot_special_summon','cannot_summon') else [scan]
            if any(re.search(pattern,clause) for clause in clauses):
                item=dict(kind=kind,tag={'dimension':'restriction','value':label},source=raw,
                          scope='player' if re.search(r'自己|对方|双方',masked) else 'this_card',
                          duration='while_applicable')
                if kind == 'selection_limit':
                    item.update(scope='this_effect')
                if re.search(r'自己不能从额外卡组(?:把怪兽)?特殊召唤',masked):
                    item.update(kind='cannot_special_summon_from_extra',from_zones=['extra'],
                                controller='self',condition='this_card_in_monster_zone' if '怪兽区域存在' in masked else 'source_clause')
                if item not in restrictions:restrictions.append(item)
    descriptions=[]
    for count in re.finditer(r'(?:这个卡名|这张卡)的[①②③④⑤⑥⑦⑧⑨⑩]+的?效果1回合(?:各能|只能|可以)(?:使用|发动)(?:最多)?\d+次',text):
        descriptions.append(dict(kind='count_limit_description',tag={'dimension':'description','value':'效果次数限制'},source=count[0]))
    if re.fullmatch(r'（注：[^。]+）',text.strip()):
        descriptions.append(dict(kind='source_compatibility_note',tag={'dimension':'description','value':'来源兼容说明'},source=text))
    if scope=='monster' and row.get('type',0)&0x80 and re.fullmatch(r'[^。]+降临[。\s]*',text):
        descriptions.append(dict(kind='ritual_association',tag={'dimension':'summon_description','value':'仪式召唤说明'},source=text,
            ritual_card_names=re.findall(r'[「『]([^」』]+)[」』]',text)))
    if re.fullmatch(r'[「『][^」』]+[」』]的(?:每个|以上|前述|这个)?效果1回合(?:各能|只能)使用1次[。\s]*',text):
        descriptions.append(dict(kind='count_limit_description',tag={'dimension':'description','value':'效果次数限制'},source=text))
    if scope=='pendulum' and re.fullmatch(r'[\s←→\d【】灵摆]*',text):
        descriptions.append(dict(kind='no_pendulum_effect',tag={'dimension':'description','value':'无灵摆效果'},source=text))
    if scope=='monster' and row.get('type',0)&1 and not row.get('type',0)&0x20:
        if row['type']&0x80 and re.search(r'[」』](?:降临|的仪式)|(?:借由|通过)[「『]',text):
            names=re.findall(r'[「『]([^」』]+)[」』]',text)
            descriptions.append(dict(kind='ritual_association',tag={'dimension':'summon_description','value':'仪式召唤说明'},
                                     source=text,ritual_card_names=names))
        elif row['type']&(0x40|0x2000|0x800000|0x4000000) and re.search(r'[＋+×]|\d+[星阶]怪兽|怪兽\d+只',text):
            descriptions.append(dict(kind='printed_materials',tag={'dimension':'summon_description','value':'召唤素材说明'},source=text))
    return restrictions,descriptions
